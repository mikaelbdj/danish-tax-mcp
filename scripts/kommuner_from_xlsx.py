"""Generate figures/kommuner/<year>.yaml from Skatteministeriet's yearly Excel file.

The files are linked from
https://svmn.dk/tal-og-metode/satser/statistik-i-kommunerne/kommuneskatteprocenter-siden-1977

Usage (from the repository root):
    uv run python scripts/kommuner_from_xlsx.py 2026 https://svmn.dk/media/.../kommuneskattesatser_2026.xlsx
"""

import datetime
import sys
import tempfile
import urllib.request
from pathlib import Path

import openpyxl
import yaml

from dk_tax.loader import slug

OUT_DIR = Path(__file__).parent.parent / "src" / "dk_tax" / "figures" / "kommuner"
EXPECTED_KOMMUNER = 98

# Column positions in the svmn.dk sheet (0-based).
COL_NAVN, COL_KODE, COL_SKAT, COL_KIRKE, COL_NEDSLAG, COL_GRUNDSKYLD = 0, 2, 5, 6, 7, 9


def read_rows(xlsx: Path) -> list[tuple]:
    # data_only: read the values Excel last saved, not formulas (the 2025 file has formulas).
    sheet = openpyxl.load_workbook(xlsx, read_only=True, data_only=True).active
    return [row for row in sheet.iter_rows(values_only=True) if isinstance(row[COL_KODE], int)]


def to_records(rows: list[tuple]) -> dict:
    kommuner = {}
    for row in rows:
        # Round away float noise like 1.1499999999999986; the source has 2 decimals.
        kommuner[slug(row[COL_NAVN])] = {
            "name": row[COL_NAVN],
            "kode": row[COL_KODE],
            "kommuneskat": round(row[COL_SKAT], 2),
            "kirkeskat": round(row[COL_KIRKE], 2),
            "skatteloftsnedslag": round(row[COL_NEDSLAG], 2),
            "grundskyldspromille": round(row[COL_GRUNDSKYLD], 2),
        }
    if len(kommuner) != EXPECTED_KOMMUNER:
        sys.exit(f"Expected {EXPECTED_KOMMUNER} kommuner, got {len(kommuner)}; check the sheet layout.")
    return kommuner


def main() -> None:
    year, url = int(sys.argv[1]), sys.argv[2]
    with tempfile.TemporaryDirectory() as tmp:
        xlsx = Path(tmp) / "kommuner.xlsx"
        urllib.request.urlretrieve(url, xlsx)
        kommuner = to_records(read_rows(xlsx))

    header = (
        f"# Municipal tax rates, income year {year}. Generated by scripts/kommuner_from_xlsx.py;\n"
        "# do not edit by hand, re-run the script instead.\n"
        "# kommuneskat, kirkeskat, skatteloftsnedslag: percent. grundskyldspromille: per mille.\n"
        "# kirkeskat applies only to members of Folkekirken.\n\n"
    )
    meta = {
        "source": url,
        "verified": datetime.date.today(),
        "status": "verified",
    }
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    out = OUT_DIR / f"{year}.yaml"
    with out.open("w") as f:
        f.write(header)
        yaml.safe_dump(meta, f, sort_keys=False)
        f.write("\n")
        yaml.safe_dump({"kommuner": kommuner}, f, sort_keys=False, allow_unicode=True)
    print(f"Wrote {len(kommuner)} kommuner to {out}")


if __name__ == "__main__":
    main()
